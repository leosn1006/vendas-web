"""Portas: o que os casos de uso precisam do mundo de fora, sem saber quem atende.

Cada porta tem um adaptador em adaptadores/ (escolhido em fabrica.py). Trocar o provedor da música
(Apiframe → conta própria no Suno) = escrever outro GeradorMusica; nada mais muda.
"""
from pathlib import Path
from typing import Protocol

from musica.dominio.modelos import Letra, PedidoGeracao, ResultadoGeracao


class ErroPassageiro(Exception):
    """Falha que vale tentar de novo (rede, 5xx ou erro transitório do provedor). Os adaptadores traduzem a do
    provedor para esta, e os casos de uso decidem a nova tentativa sem conhecer o provedor."""


class GeradorMusica(Protocol):
    nome: str   # gravado em musicas.provedor

    def criar(self, pedido: PedidoGeracao, webhook_url: str | None) -> str:
        """Manda compor; devolve o id do trabalho no provedor. ErroGerador se recusar."""

    def consultar(self, job_id: str) -> ResultadoGeracao:
        """Como está o trabalho. Falha de rede = GERACAO_ANDAMENTO (tenta de novo depois)."""

    def webhook_valido(self, corpo: bytes, cabecalhos: dict) -> str | None:
        """Se o aviso veio mesmo do provedor, o job_id dele; senão None."""


class EscritorLetra(Protocol):
    modelo: str   # gravado em musicas.modelo_letra

    def escrever(self, instrucoes: str, respostas: dict, letra_anterior: str | None = None,
                 ajuste: str | None = None) -> Letra:
        """Letra a partir do quiz (ou o ajuste pedido sobre a letra anterior). ErroLetra se falhar."""


class Transcritor(Protocol):
    def palavras(self, arquivo_mp3: Path, dica: str) -> list[dict]:
        """Tempos de cada palavra cantada: [{'palavra', 'inicio', 'fim'}]."""


class Audio(Protocol):
    def baixar(self, url: str, destino: Path) -> None: ...

    def cortar_previa(self, origem: Path, destino: Path, inicio: float, segundos: int) -> None: ...


class Video(Protocol):
    max_fotos: int

    def preparar_foto(self, origem, destino: Path) -> None: ...

    def montar(self, fotos: list[Path], musica: Path, saida: Path, titulo: str, para: str, de: str,
               legenda_ass: Path | None = None) -> None: ...


class Repositorio(Protocol):
    """Todo o acesso ao banco do módulo (adaptadores/repositorio_mysql.py)."""

    def criar(self, produto_id: int, respostas: dict, email: str, whatsapp: str, ip: str,
              pedido_origem_id: int | None, dominio: str | None) -> dict: ...
    def por_id(self, musica_id: int) -> dict | None: ...
    def por_token(self, token: str) -> dict | None: ...
    def por_job(self, job_id: str) -> dict | None: ...
    def do_pedido(self, pedido_id: int) -> dict | None: ...
    def atualizar(self, musica_id: int, **campos) -> None: ...
    def trocar_status(self, musica_id: int, de: str, para: str) -> bool: ...
    def geracoes_recentes(self, email: str, ip: str, horas: int = 24) -> int: ...
    def musicas_criadas_recentes(self, email: str, ip: str, horas: int = 24) -> int: ...
    def videos_parados(self, minutos: int) -> list[dict]: ...
    def vincular_pedido(self, musica_id: int, pedido_id: int) -> None: ...
    def pedido_pago(self, pedido_id: int) -> dict | None: ...
    def pedido_por_guid(self, guid: str) -> dict | None: ...
    def recursos_do_pedido(self, pedido_id: int) -> set[str]: ...
    def marcar_liberada(self, musica_id: int, pedido_id: int) -> bool: ...
    def pagas_sem_liberar(self) -> list[int]: ...
    def presentes_para_enviar(self) -> list[dict]: ...
    def marcar_presente_enviado(self, musica_id: int) -> bool: ...
    def presente_por_devolucao(self, thread_id: str, recusados: list[str]) -> dict | None: ...
    def presentes_sem_confirmacao(self, minutos: int) -> list[dict]: ...
    def por_wamid_presente(self, wamid: str) -> dict | None: ...
    def marcar_presente_wa(self, musica_id: int, status: str) -> bool: ...
    def numero_avisos(self, produto_id: int) -> str | None: ...
    def presente_wa_sem_wamid(self, telefone: str) -> bool:
        """Há presente_surpresa saindo agora (há poucos minutos) para este número, ainda sem wamid gravado?"""
    def candidatas_lembrete(self) -> list[dict]: ...
    def series_lembrete(self) -> dict:
        """{(chave_email, etapa): {'inicio', 'desde', 'enviados', 'ultimo_em', 'musica_id', 'musica_status'}} das
        séries recentes (musica_id/_status: a música da vez e em que pé ela está — sem eles a troca de música não
        recomeça o relógio e uma "outra versão" não é esperada)."""
    def salvar_serie(self, chave_email: str, etapa: str, inicio, desde, enviados: int, ultimo_em,
                     musica_id: int) -> None: ...
    def parar_lembretes_email(self, chave_email: str) -> None: ...
    def musicas_vendidas(self, busca: str = '', limite: int = 200) -> list[dict]: ...
    def venda_da_musica(self, musica_id: int) -> dict | None: ...
    def rascunho_ativo(self, musica_id: int) -> dict | None:
        """Admin "refazer a música": o rascunho ainda não usado desta música (musicas.rascunho_de)."""
    def marcar_rascunho_usado(self, rascunho_id: int, usado: bool = True) -> bool: ...
    def paradas(self, status: str, minutos: int) -> list[int]: ...
    def nao_pagas_antigas(self, dias: int) -> list[dict]: ...
    def apagar(self, musica_id: int) -> None: ...
    def remetente_do_produto(self, produto_id: int) -> dict: ...
    def produto_musica(self) -> dict | None: ...
    def empresa_do_produto(self, produto: dict) -> dict: ...


class Agenda(Protocol):
    """Trabalho em segundo plano (Celery no sistema; uma lista em memória nos testes)."""

    def escrever_letra(self, musica_id: int, ajuste: str | None = None) -> None: ...
    def consultar(self, musica_id: int, depois_de_segundos: int = 0) -> None: ...
    def fazer_video(self, musica_id: int) -> None: ...
    def enviar_presentes(self) -> None: ...
    def whatsapp_comprador(self, musica_id: int) -> None: ...
    def reler_status_whatsapp(self, statuses: list, depois_de_segundos: int) -> None: ...


class Notificador(Protocol):
    """Mensagens para a cliente (e-mail; WhatsApp quando houver número)."""

    def email(self, produto_id: int, destino: str, assunto: str, html: str, cc: str | None = None) -> str | None:
        """Envia; devolve o thread do Gmail (None no dev, que não envia)."""

    def whatsapp(self, telefone: str, modelo: str, variaveis: list[str], payload_botao: str | None = None,
                 produto_id: int | None = None) -> str | None:
        """Template aprovado pelo número só de avisos do produto da música; devolve o wamid (None = WhatsApp
        desligado). Erro que vale tentar de novo: ErroPassageiro."""

    def whatsapp_texto(self, telefone: str, texto: str, produto_id: int | None = None) -> str | None:
        """Texto livre (só dentro da janela de 24 h aberta pela pessoa, ex.: depois de tocar num botão)."""

    def equipe(self, mensagem: str) -> None: ...
